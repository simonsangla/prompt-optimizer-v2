// Deterministic regression gate over the stress fixtures (K7, mission-os#617).
//
// Why this exists next to the other two harnesses, rather than inside them:
// - eval/run-eval.mjs needs a live Ollama and writes a report; it asserts
//   nothing, so it cannot fail a regression in CI or on a laptop with no model.
// - eval/adversarial.mjs asserts, but on seven synthetic corruptions of one
//   source sentence.
// Neither pins "these real prompts must keep producing these extraction and
// check outcomes". Every expectation below was measured, not guessed, and the
// prompts are the ones that broke the kernel on 2026-09-04.
//
// Runs offline in milliseconds. Exit code 1 on any regression.
// Run: node eval/stress.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { protectedSpans } from '../lib/extract.mjs';
import { spanRetention, contentCoverage, languageMatch, guessScript, guessLanguage } from '../lib/verify.mjs';

const fixtures = JSON.parse(await readFile(new URL('./fixtures.json', import.meta.url), 'utf8'));
const cases = fixtures.filter((f) => f.expect);
const failures = [];
const rows = [];

for (const f of cases) {
  const t0 = Date.now();
  const spans = protectedSpans(f.input);
  const extractMs = Date.now() - t0;
  const values = spans.map((s) => s.span);
  const negated = spans.filter((s) => s.negated).map((s) => s.span);
  const problems = [];
  const e = f.expect;

  for (const want of e.spansInclude || []) if (!values.includes(want)) problems.push(`missing span ${JSON.stringify(want)}`);
  for (const no of e.spansExclude || []) if (values.includes(no)) problems.push(`unwanted span ${JSON.stringify(no)}`);
  for (const want of e.spansNegated || []) if (!negated.includes(want)) problems.push(`span ${JSON.stringify(want)} should be negated, got [${negated.join(', ')}]`);
  if (e.script && guessScript(f.input) !== e.script) problems.push(`script ${guessScript(f.input)} != ${e.script}`);
  if (e.language && guessLanguage(f.input) !== e.language) problems.push(`language ${guessLanguage(f.input)} != ${e.language}`);
  if (e.retentionPassesOn && !spanRetention(spans, e.retentionPassesOn).passed) problems.push('retention should pass on the faithful rewrite');
  if (e.retentionFailsOn && spanRetention(spans, e.retentionFailsOn).passed) problems.push('retention should fail on the substring decoy');
  if (e.coverageFailsOn && contentCoverage(f.input, e.coverageFailsOn).passed) problems.push('coverage should fail when requirements are demoted to open questions');
  if (e.translationCaught && languageMatch(f.input, e.translationCaught).passed) problems.push('translation should be caught');
  if (e.languageMatchOn && !languageMatch(f.input, e.languageMatchOn).passed) problems.push('faithful same-language rewrite should pass');
  if (e.extractionUnderMs && extractMs > e.extractionUnderMs) problems.push(`extraction took ${extractMs}ms > ${e.extractionUnderMs}ms`);

  rows.push({ id: f.id, category: f.category, spans: spans.length, negated: negated.length, extractMs, ok: problems.length === 0 });
  if (problems.length) failures.push({ id: f.id, problems });
  console.log(`${problems.length ? 'FAIL' : 'ok  '}  ${f.id}${problems.length ? ' - ' + problems.join('; ') : ''}`);
}

const md = `# Intact - deterministic stress evidence

Generated by \`node eval/stress.mjs\`. Offline: no model, no network.
Fixtures: the ${cases.length} prompts that broke the kernel on 2026-09-04
(mission-os#617) - garbled, multilingual, very short, very long, and meaning
traps - each pinned to the extraction and check outcomes measured after K0-K6.

| fixture | category | spans | negated | result |
|---|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${r.category} | ${r.spans} | ${r.negated} | ${r.ok ? 'ok' : 'FAIL'} |`).join('\n')}

**${rows.filter((r) => r.ok).length}/${rows.length} fixtures hold.**
${failures.length ? '\n## Regressions\n' + failures.map((f) => `- **${f.id}**: ${f.problems.join('; ')}`).join('\n') : ''}

Timings are asserted (\`extractionUnderMs\`) but not printed: a report that
carries wall-clock numbers changes on every run, so the gate would dirty the
working tree each time it passed and nobody would run it twice.

These are deterministic-layer expectations only. LLM-mode behaviour is
nondeterministic and is measured separately by \`node eval/run-eval.mjs\`,
which needs a running Ollama.
`;
await writeFile(new URL('./EVIDENCE-stress.md', import.meta.url), md);

console.log(`\n${rows.filter((r) => r.ok).length}/${rows.length} stress fixtures hold`);
console.log('Wrote eval/EVIDENCE-stress.md');
process.exit(failures.length ? 1 : 0);
